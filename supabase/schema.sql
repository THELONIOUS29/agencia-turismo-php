-- Esquema PostgreSQL para Supabase.
-- Ejecutar en Supabase Dashboard > SQL Editor.

create schema if not exists agencia;
set search_path to agencia, public;

do $$
begin
  if not exists (
    select 1
    from pg_type t
    join pg_namespace n on n.oid = t.typnamespace
    where t.typname = 'rol_usuario'
      and n.nspname = 'agencia'
  ) then
    create type rol_usuario as enum ('admin', 'usuario', 'visitante');
  end if;
end
$$;

create table if not exists destinos (
  id_destino bigint generated by default as identity primary key,
  nombre_destino varchar(255) not null,
  foto_destino bytea not null default decode('', 'hex'),
  foto_destino_url text,
  descripcion text,
  resenas integer,
  constraint destinos_resenas_check check (resenas is null or resenas >= 0)
);

create table if not exists usuarios (
  id_user bigint generated by default as identity primary key,
  usuario varchar(50) not null unique,
  rol rol_usuario default 'usuario',
  fotou bytea not null default decode('', 'hex'),
  foto_u_url text,
  contra varchar(255) not null,
  nombre varchar(50) not null,
  apellido varchar(50) not null default '',
  correo varchar(100) not null unique,
  cedula varchar(100) not null default '',
  telefono varchar(10),
  direccion varchar(100) not null default '',
  fecha_registro timestamptz not null default now()
);

create table if not exists paquetes (
  id_paquete bigint generated by default as identity primary key,
  nombre_paquete varchar(255) not null,
  descripcion text,
  precio numeric(10,2) not null,
  fecha_inicio date not null,
  fecha_fin date not null,
  id_destino bigint not null references destinos(id_destino) on delete cascade,
  cantidad_personas_max integer,
  constraint paquetes_precio_check check (precio >= 0),
  constraint paquetes_fechas_check check (fecha_fin >= fecha_inicio),
  constraint paquetes_personas_check check (cantidad_personas_max is null or cantidad_personas_max >= 0)
);

create table if not exists reservas (
  id_reserva bigint generated by default as identity primary key,
  fecha_reserva timestamptz not null default now(),
  id_user bigint not null references usuarios(id_user) on delete cascade,
  id_paquete bigint not null references paquetes(id_paquete) on delete cascade,
  cantidad_personas integer not null,
  constraint reservas_personas_check check (cantidad_personas > 0)
);

create index if not exists paquetes_id_destino_idx on paquetes(id_destino);
create index if not exists reservas_id_user_idx on reservas(id_user);
create index if not exists reservas_id_paquete_idx on reservas(id_paquete);

-- Si usas AGENCIA_DB_SCHEMA=agencia en PHP, estas tablas se resolveran
-- automaticamente como agencia.usuarios, agencia.destinos, etc.

